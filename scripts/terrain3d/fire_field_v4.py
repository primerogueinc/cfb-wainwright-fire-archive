"""Arrival-time field for the 3D animation taken entirely from working model v4.

  before 3:16 p.m.  v4 case v4b (best-fit morning fire, start ~5:00 a.m.):
                    model_v4/arrival_prefront_v4b_2x_lb3.0_0500.tif (hours after midnight)
  start of the run  that fire joined with the outline of the 12:17 and 2:49 p.m.
                    detections, as post_front.py does
  after 3:16 p.m.   one of v4's 30 post-front fires for case v4b, the one that fits
                    the final scar best: wind fixed from 315 deg, head spread 8 km/h,
                    steady shape (Jaccard 0.547; arrival at the Range 2 point 3:21,
                    road head 3:25; v4 weighted medians 3:21 and 3:26). Regenerated by
                    running v4's post_front.py grid step (arr_S4_fixed315_8.0_steady.npy,
                    minutes after 3:00 p.m., 40 m grid).

Scar cells neither fire reaches are "timing unknown" (shown only at the end).

Run: python3 fire_field_v4.py LAYERDIR PREFRONT_TIF POSTFRONT_DIR
"""
import sys, os, json
import numpy as np
import rasterio
from rasterio.warp import reproject, Resampling
from rasterio.transform import from_origin
from rasterio.features import rasterize
from shapely.geometry import MultiPoint, mapping
from PIL import Image

Ld, PRE, PF = sys.argv[1:4]
RUN = os.environ.get('V4_RUN', 'S4_fixed315_8.0_steady')
P = json.load(open(os.path.join(Ld, 'points.json')))
G = P['grid']; RES = G['res']; W, H = G['w'], G['h']
TG = from_origin(G['x0'], G['y0'] + H * RES, RES, RES)
T_SHIFT = 15 * 60 + 16
scar5 = np.asarray(Image.open(os.path.join(Ld, 'scar.png'))) > 127
scar = scar5.reshape(H, 2, W, 2).mean(axis=(1, 3)) >= 0.5


def to_grid(arr, transform, crs):
    out = np.full((H, W), np.nan, np.float32)
    reproject(arr.astype(np.float32), out, src_transform=transform, src_crs=crs, src_nodata=np.nan,
              dst_transform=TG, dst_crs=G['crs'], dst_nodata=np.nan, resampling=Resampling.bilinear)
    return out


with rasterio.open(PRE) as r:
    pre = to_grid(r.read(1), r.transform, r.crs) * 60          # minutes after midnight
minx, maxy, R40, h40, w40 = np.load(os.path.join(PF, 'meta.npy'))
T40 = from_origin(minx, maxy, R40, R40)
post = to_grid(np.load(os.path.join(PF, f'arr_{RUN}.npy')), T40, G['crs']) + 15 * 60  # minutes after midnight

arr = np.full((H, W), np.nan, np.float32)
m_pre = np.isfinite(pre) & (pre <= T_SHIFT)
arr[m_pre] = pre[m_pre]

# 12:17/2:49 detection outline: v4 joins it to the 3:16 fire. Cells v4b hasn't reached keep the
# run's start time (they are part of the fire at 3:16); give them 2:49, when VIIRS saw fire there.
ls = [h for h in P['hotspots'] if h['source'] == 'LANDSAT_NRT' and '12:17' in (h['time_mdt'] or '')]
vi = [h for h in P['hotspots'] if h['source'] == 'VIIRS_NOAA20_NRT' and '14:49' in (h['time_mdt'] or '')]
hull = MultiPoint([(h['x'], h['y']) for h in ls + vi]).convex_hull
hullm = rasterize([(mapping(hull), 1)], out_shape=(H, W), transform=from_origin(0, H * RES, RES, RES),
                  dtype=np.uint8).astype(bool)
fill = hullm & ~m_pre
arr[fill] = 14 * 60 + 49

m_post = np.isfinite(post) & ~np.isfinite(arr) & (post > T_SHIFT)
arr[m_post] = post[m_post]
unk = scar & ~np.isfinite(arr)
np.save(os.path.join(Ld, 'arrival_min.npy'), arr)
np.save(os.path.join(Ld, 'unknown.npy'), unk)
json.dump({'T_SHIFT': T_SHIFT, 'run': RUN, 'source': 'working model v4, case v4b'},
          open(os.path.join(Ld, 'fire_meta.json'), 'w'))
km2 = lambda m: m.sum() * RES * RES / 1e6
print(f'v4b morning fire {km2(m_pre):.2f} km2; outline fill {km2(fill):.2f}; post-front {km2(m_post):.2f}; '
      f'scar not reached {km2(unk):.2f} km2 of {km2(scar):.2f}')
for k in ('Range 2', 'Roadhead'):
    v = P['pov'][k]; r, c = int(H - 1 - v['y'] / RES), int(v['x'] / RES)
    a = arr[r, c]; print(f'  {k}: fire arrives {int(a // 60)}:{a % 60:04.1f}')
